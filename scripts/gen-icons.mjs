// One-off: extracts the brand SVG paths we use from simple-icons into src/lib/brand-icons.ts
// so the site doesn't ship the whole icon package. Run: npm i -D simple-icons && node scripts/gen-icons.mjs
import * as si from "simple-icons";
import fs from "node:fs";
const want = ["python","cplusplus","looker","pytorch","huggingface","langchain","apacheairflow","docker","googlecloud","githubactions","googlebigquery","pydantic","warnerbros","volkswagen","github","linkedin"];
const out = {};
for (const w of want) {
  const i = si["si" + w[0].toUpperCase() + w.slice(1)];
  if (!i) throw new Error("missing " + w);
  out[w] = { title: i.title, hex: i.hex, path: i.path };
}
fs.writeFileSync("src/lib/brand-icons.ts",
  "// Generated by scripts/gen-icons.mjs (paths from simple-icons, CC0)\nexport const brandIcons = " + JSON.stringify(out, null, 2) + " as const;\nexport type BrandKey = keyof typeof brandIcons;\n");
console.log("ok", Object.keys(out).length);
